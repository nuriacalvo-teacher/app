# Flores que se mecen: (polígono o elipse, y_base, y_cima, fase 0-1, amplitud 0-1)
def ellipse(cx, cy, rx, ry, n=24):
    import math
    return [(cx + rx * math.cos(2 * math.pi * i / n), cy + ry * math.sin(2 * math.pi * i / n)) for i in range(n)]

